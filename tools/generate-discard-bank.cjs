const fs=require('fs'),path=require('path'),A=require('../efficiency');
const rng=A.random(20261115),pick=a=>a[Math.floor(rng()*a.length)],bank=[],seen=new Set();
for(const players of [4,3]){
  let attempts=0;
  while(bank.filter(q=>q.players===players).length<360){
    if(++attempts>60000)throw Error('Generation limit');
    const pool=Array.from({length:34},(_,t)=>t).filter(t=>A.allowed(t,players));let hand=[];
    const pair=pick(pool);hand.push(pair,pair);
    for(let i=0;i<4;i++){
      if(rng()<.78){const suit=pick(players===3?[1,2]:[0,1,2]),t=suit*9+Math.floor(rng()*7);hand.push(t,t+1,t+2);}
      else{const t=pick(pool);hand.push(t,t,t);}
    }
    const changes=2+Math.floor(rng()*4);
    for(let i=0;i<changes;i++)hand[Math.floor(rng()*14)]=pick(pool);
    hand.sort((a,b)=>a-b);const c=A.counts(hand),key=players+':'+hand.join(',');
    if(c.some(n=>n>4)||[4,13,22].some(t=>c[t]>3)||seen.has(key)||A.complete(c))continue;
    const r=A.analyze({hand,players}),s=r.rows[0].shanten,best=r.rows.filter(x=>x.best);
    if(s<0||s>2||best.length>3||r.rows.every(x=>x.best)||r.rows[0].total<4)continue;
    const local=bank.filter(q=>q.players===players),wanted=local.length<120?0:local.length<240?1:2;
    if(s!==wanted)continue;
    const pairs=c.filter(n=>n>=2).length;
    const topic=pairs>=5?'七对子与面子手':pairs>=3?'对子与复合搭子':s===0?'听牌宽度':r.rows.some(x=>x.shanten>s)?'保留有效搭子':'进张数量比较';
    bank.push({id:`${players===3?'S':'Y'}${String(local.length+1).padStart(3,'0')}`,players,hand,shanten:s,answers:best.map(x=>x.discard),total:r.rows[0].total,topic});seen.add(key);
  }
}
const text='/* 720 independently generated and validated Queyou efficiency exercises.\n * Generated by tools/generate-discard-bank.cjs. */\n(function(root){const bank='+JSON.stringify(bank)+';if(typeof module!==\'undefined\'&&module.exports)module.exports=bank;root.MJDiscardBank=bank;})(typeof window===\'undefined\'?globalThis:window);\n';
fs.writeFileSync(path.join(__dirname,'..','discard-bank.js'),text);
